// Package subscriptionpublication owns deterministic client representation
// rendering, planning, and atomic publication.
//
// Its Interface renders one complete typed Connection Profile source into
// byte-stable raw, standard-base64, v2rayN, Shadowrocket candidate, Mihomo,
// sing-box, and Karing artifacts. It preserves the fixed URI and structured-
// document contracts, canonical order, stable routing references, deliberate
// omissions, safe encoding, IPv6, normal TLS verification, and the exact
// enabled-or-disabled Hysteria2 obfuscation choice. Karing receives
// the validated five-Connection-Profile sing-box document; both representations
// explicitly report enabled VLESS XHTTP as Not offered rather than substituting
// another Connection Profile; deliberate disablement takes precedence and is
// reported as Disabled. Shadowrocket receives the six-URI base64 candidate, but
// every rendered Connection Profile remains pending Owner Acceptance.
// Caller-supplied pinned Mihomo and sing-box validators must accept the full
// documents. Rendering fails closed with a secret-safe error when validation or
// any required fact or Client Access Value is unavailable. Artifact bodies
// require explicit field access; ordinary Go formatting and JSON rendering
// remain redacted.
//
// PrepareClientAccessMutation uses operating-system cryptographic randomness to
// replace the 256-bit subscription token. Token-only rotation preserves all
// Connection Profile credentials and states that already downloaded profiles
// remain valid. Coordinated revocation also replaces every credential across
// all six Connection Profiles while preserving their settings and enablement.
// State requires a reviewed Subscription Publication Plan for every credential,
// port, address, certificate, compatibility release, enablement, and software-
// version input represented by the publication. Client Access mutation values,
// routes, and JSON remain redacted unless a caller explicitly requests one
// approved route.
//
// Plan binds one complete validated eight-file candidate to the exact Desired
// State revision, relevant managed-input checksums, compatibility definition,
// selected address, typed Connection Profile source, and Release Identity. Its
// one-use Apply contributes one reversible Subscription Publication step and
// Required pre- and post-publication checks to System Changes. State carries
// the protected bodies and minimum Serving configuration into that existing
// transaction; the filesystem Adapter atomically exchanges one immutable
// nine-file serving generation into /var/lib/sbxr/subscriptions/current/.
// Desired State publishes exactly once
// only after activation and pre-publication health, and Complete requires
// post-publication serving agreement.
//
// Rendering, preparation, storage, activation, health, publication, or
// agreement failure is secret-safe and fails closed. Before activation it
// changes nothing; afterward System Changes restores the exact prior complete
// set and Desired State, or reports Recovery Required when lineage or rollback
// cannot be proven. Plans and prepared artifact authorities cannot be reused.
// Subscription Serving receives only the active immutable serving snapshot;
// it receives no Desired State, renderer, typed source, or arbitrary filesystem
// access.
//
// View returns only token-free publication status, the exact seven named
// representation identities, actual counts and omissions, the selected
// subscription address, conservative Base64 fallback metadata, and agreement
// with proven Desired State. Stale compatibility definitions require
// regeneration. It returns no token or generated body, and User-Agent is never
// authentication, authorization, or compatibility proof.
//
// The package does not serve subscriptions, read current Desired State, mutate
// live Connection Profiles, expose credentials through diagnostics, substitute
// an unsupported Connection Profile, or claim maintained-client or Owner Acceptance.
